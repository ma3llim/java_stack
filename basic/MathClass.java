public class MathClass {
    public static void main(String[] args) {
        System.out.println("Absolute Value: " + Math.abs(-4));
        System.out.println("Rounds Up: " + Math.ceil(4.4));
        System.out.println("Rounds Down: " + Math.floor(4.9));
        System.out.println("Rounds to nearest integer: " + Math.round(10.9));
        System.out.println("Maximun: " + Math.max(10, 64));
        System.out.println("Minimum: " + Math.min(2, 9));
        System.out.println("Power Calcluation: " + Math.pow(5, 2));
        System.out.println("Square Root: " + Math.sqrt(4));
        System.out.println("Random Number Generation: " + Math.random());
        System.out.println("Exponential function: " + Math.exp(4));
        System.out.println("Logarithmic function: " + Math.log(4));
    }
}
